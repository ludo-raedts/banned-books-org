-- ============================================================================
-- Register layer — lean entries for very large historical ban lists.
--
-- Some official lists run to tens of thousands of titles (SBZ "Liste der
-- auszusondernden Literatur" 1946–1953 ≈ 31k book entries) or carry rows too
-- thin to import as books (Index Librorum Prohibitorum 1877: ~1.1k held rows
-- without decree year / identifiable author).
-- Importing them as books would mint tens of thousands of thin pages. Instead:
--   * register_lists   — one row per list (context, framing, source, counts)
--   * register_entries — one row per printed entry, NO book/author rows, no
--                        enrichment. matched_book_id is set only when the entry
--                        is a book we already carry (tier a; that book also
--                        gets a real ban row via the normal commit-lib).
-- Pages: /registers/[slug] and /registers/[slug]/[letter] read entries by
-- (list_id, letter) — one index range scan, statically cached.
--
-- Disk-IO: ~35k rows × ~300 B ≈ 12 MB heap+indexes for SBZ. No per-request
-- aggregation: counts are denormalised into register_lists by the importer
-- (entry_count/book_count/matched_count), so country/stats pages read one row
-- per list. No matview, no triggers.
-- ============================================================================

CREATE TABLE IF NOT EXISTS "public"."register_lists" (
  "id"            smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "slug"          text        NOT NULL UNIQUE,
  "title"         text        NOT NULL,          -- original title as printed
  "title_en"      text,
  "issuer"        text        NOT NULL,          -- issuing authority
  "country_code"  char(2)     NOT NULL REFERENCES "public"."countries"("code"),
  "year_start"    smallint    NOT NULL,
  "year_end"      smallint,
  -- how the site frames the list; 'denazification' lists are labelled apart
  -- from repression censorship (cf. Liste Otto victims vs. real bans)
  "framing"       text        NOT NULL
                  CONSTRAINT "register_lists_framing_check"
                  CHECK (framing IN ('denazification', 'repression', 'religious', 'other')),
  "intro_md"      text,                          -- context intro shown on the list page
  "source_name"   text        NOT NULL,
  "source_url"    text        NOT NULL,
  "licence_note"  text,
  "page_url_template" text,                      -- optional, e.g. 'https://archive.org/details/x/page/n{page}' ({page} = printed_page)
  "entry_count"   integer     NOT NULL DEFAULT 0, -- all book+blanket entries
  "book_count"    integer     NOT NULL DEFAULT 0, -- kind = 'book'
  "matched_count" integer     NOT NULL DEFAULT 0, -- entries with matched_book_id
  "created_at"    timestamptz NOT NULL DEFAULT now(),
  "updated_at"    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "public"."register_entries" (
  "id"              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "list_id"         smallint    NOT NULL REFERENCES "public"."register_lists"("id") ON DELETE CASCADE,
  "source_key"      text        NOT NULL,        -- stable key from the stage-0 file (idempotent re-import)
  "edition"         text        NOT NULL,        -- e.g. '1946', '1947' (Nachtrag I), …
  "kind"            text        NOT NULL
                    CONSTRAINT "register_entries_kind_check"
                    CHECK (kind IN ('book', 'blanket', 'group', 'periodical', 'rescission')),
  "letter"          char(1)     NOT NULL,        -- A–Z or '#', from the printed headword
  "sort_key"        text        NOT NULL,        -- folded headword + title, for in-letter order
  "printed_author"  text,
  "author_display"  text,
  "title"           text        NOT NULL,
  "imprint"         text,
  "pub_year"        smallint,
  "ban_year"        smallint,                    -- NULL = no per-entry date; the list's year_start applies
  "note"            text,
  "source_url"      text,                        -- deep link (transcription page / scan page); NULL → list source_url
  "printed_page"    smallint,
  "locator"         text,                        -- free-text position in the source, e.g. "p. 109, l. 23"
  "matched_book_id" bigint      REFERENCES "public"."books"("id") ON DELETE SET NULL,
  "created_at"      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "register_entries_list_source_key" UNIQUE ("list_id", "source_key")
);

-- Letter pages: WHERE list_id = $1 AND letter = $2 ORDER BY sort_key
CREATE INDEX IF NOT EXISTS "idx_register_entries_letter"
  ON "public"."register_entries" ("list_id", "letter", "sort_key");
-- Book page "also on <list>" lookup + FK delete support; partial = tiny.
CREATE INDEX IF NOT EXISTS "idx_register_entries_matched_book"
  ON "public"."register_entries" ("matched_book_id") WHERE "matched_book_id" IS NOT NULL;

ALTER TABLE "public"."register_lists"   ENABLE ROW LEVEL SECURITY;
ALTER TABLE "public"."register_entries" ENABLE ROW LEVEL SECURITY;
CREATE POLICY "public read register_lists"   ON "public"."register_lists"   FOR SELECT TO "anon" USING (true);
CREATE POLICY "public read register_entries" ON "public"."register_entries" FOR SELECT TO "anon" USING (true);
GRANT SELECT ON "public"."register_lists", "public"."register_entries" TO "anon", "authenticated";
GRANT ALL    ON "public"."register_lists", "public"."register_entries" TO "service_role";

COMMENT ON TABLE "public"."register_lists" IS
  'Very large historical ban lists kept as a lean register (no book pages). Counts are denormalised by the importer; never summed into distinct-books metrics.';
COMMENT ON TABLE "public"."register_entries" IS
  'One printed entry of a register list. matched_book_id only for books already in the catalogue (tier a).';
